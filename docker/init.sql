-- Инициализация схемы БД ИСППР по техническому обслуживанию оборудования.
-- Выполняется образом pgvector ОДИН раз — при первой инициализации пустого тома данных.
-- При изменении этого файла пересоздать БД: docker compose down -v && docker compose up.

CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================================================
-- A. Векторное хранилище документации (замена Pinecone)
-- ============================================================================
CREATE TABLE document_chunks (
    id         TEXT PRIMARY KEY,             -- SHA256[:32] от f"{doc_id}::{source}::{chunk_index}"
    doc_id     TEXT NOT NULL,                -- UUID загрузки (RAGPipeline.ingest)
    source     TEXT NOT NULL DEFAULT '',     -- имя файла-источника
    page       INTEGER NOT NULL DEFAULT 0,   -- номер страницы (1-индекс)
    text       TEXT NOT NULL,                -- содержимое чанка
    embedding  vector(1536) NOT NULL,        -- OpenAI text-embedding-3-small
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Лексический индекс для гибридного поиска (русский стеммер), считается автоматически
    tsv        tsvector GENERATED ALWAYS AS (to_tsvector('russian', text)) STORED
);

-- HNSW-индекс для косинусного поиска (оператор <=>)
CREATE INDEX idx_chunks_embedding ON document_chunks
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

-- GIN-индекс для полнотекстового (лексического) поиска — гибрид dense + FTS
CREATE INDEX idx_chunks_tsv ON document_chunks USING GIN (tsv);

-- Для фильтрации/удаления по документу
CREATE INDEX idx_chunks_doc_id ON document_chunks (doc_id);

-- ============================================================================
-- B. База оборудования (инструмент агента query_equipment_db)
-- ============================================================================
CREATE TYPE equipment_status AS ENUM (
    'в эксплуатации',
    'в ремонте',
    'выведено из эксплуатации'
);

CREATE TABLE equipment (
    equipment_id         TEXT PRIMARY KEY,           -- натуральный ключ: 'ТМ-630/10-1'
    type                 TEXT NOT NULL,              -- 'Трансформатор масляный силовой 630 кВА'
    commissioned_date    DATE NOT NULL,              -- дата ввода в эксплуатацию
    last_inspection_date DATE NOT NULL,              -- дата последнего осмотра
    status               equipment_status NOT NULL DEFAULT 'в эксплуатации',
    location             TEXT                        -- расположение (опционально)
);

CREATE INDEX idx_equipment_last_inspection ON equipment (last_inspection_date);

